using Autodesk.Revit.DB;
using Autodesk.Revit.DB.Architecture;
using SunnyParameterManager.Core;
using SunnyParameterManager.Bridge;

int count = 0;
void Check(bool ok, string name) { if (!ok) throw new Exception("FAIL " + name); count++; Console.WriteLine("PASS " + name); }
void Reject(Action action, string name) { bool rejected = false; try { action(); } catch (InvalidOperationException) { rejected = true; } Check(rejected, name); }
var model = new ModelSnapshot { Path = "A.rvt", CanonicalPath = "A.rvt", Identity = "model" };
var doc = new Document();
var revit = new RevitLinkType { Name = "Revit 정의", Pinned = true, FileReference = new() { ExternalFileReferenceType = ExternalFileReferenceType.RevitLink } };
var nested = new RevitLinkType { Name = "중첩 링크", IsNestedLink = true };
var cad = new CADLinkType(); var point = new PointCloudType(); var image = new ImageType(); var topo = new TopographyLinkType();
var coord = new ElementType { Category = new() { Id = new((long)BuiltInCategory.OST_Coordination_Model) } };
var importedType = new ElementType();
doc.Elements.AddRange([revit, nested, cad, point, image, topo, coord, importedType]);
doc.Elements.AddRange([new RevitLinkInstance { TypeId = revit.Id }, new RevitLinkInstance { TypeId = nested.Id }, new ImportInstance { TypeId = cad.Id, IsLinked = true }, new ImportInstance { TypeId = importedType.Id }, new PointCloudInstance { TypeId = point.Id }, new ImageInstance { TypeId = image.Id }, new Element { TypeId = topo.Id }, new Element { TypeId = coord.Id }]);
doc.Dependencies[revit.Id.Value] = [nested.Id.Value];
var tag = new Element { Name = "링크 태그" }; var wall = new Element { Name = "보존할 벽" };
doc.Elements.AddRange([tag, wall]); doc.Dependencies[revit.Id.Value].Add(tag.Id.Value);
var plan = LinkRemovalEngine.Preview(doc, model);
Check(plan.Targets.Count == 16 && plan.Affected.Count == 17, "종류별 정의/배치와 태그까지 삭제 영향 수집");
Check(doc.Elements.Count == 18, "삭제 영향 검사는 롤백하여 모델 복원");
Check(plan.DependentCount == 1 && plan.Affected.Single(x => x.UniqueId == tag.UniqueId).Name == "링크 태그", "종속 요소 이름과 개수 표시");
Check(plan.Targets.Any(x => x.UniqueId == importedType.UniqueId), "일반 유형으로 표현된 가져오기 정의도 포함");
Check(plan.Targets.Single(x => x.UniqueId == nested.UniqueId).Root == false && !doc.LastRequested.Contains(nested.Id), "중첩 링크는 직접 삭제하지 않고 상위 삭제 영향으로 처리");
Check(plan.Targets.Single(x => x.UniqueId == revit.UniqueId).Pinned, "고정된 링크 명시 표시");
Reject(() => LinkRemovalEngine.Prepare(doc, model, plan, false), "종속 요소 별도 승인 누락 차단");
var action = LinkRemovalEngine.Prepare(doc, model, plan, true); action.Delete(); action.Verify();
Check(doc.Elements.Count == 1 && doc.Elements[0] == wall, "모든 링크 정의까지 제거하고 일반 벽 보존");
Check(LinkRemovalEngine.Collect(doc, model).Targets.Count == 0, "삭제 후 남은 정의/배치 0 재검증");
LinkRemovalEngine.CheckComplete(doc, model); Check(true, "저장·동기화 후 최종 링크 없음 확인");
doc.Elements.Add(new ImageType()); Reject(() => LinkRemovalEngine.CheckComplete(doc, model), "동기화 중 추가된 링크를 완전 제거 성공으로 보고하지 않기");
Reject(() => LinkRemovalEngine.Prepare(doc, model, plan, true), "이미 처리한 삭제 계획 재실행 차단");
doc = new(); doc.Elements.Add(new CADLinkType()); plan = LinkRemovalEngine.Preview(doc, model);
doc.Elements.Add(new ImageType()); Reject(() => LinkRemovalEngine.Prepare(doc, model, plan, true), "검사 후 추가된 링크가 있으면 전체 보류");
doc = new(); var cloud = new RevitLinkType(); cloud.Resources.Add("resource", new()); doc.Elements.Add(cloud);
plan = LinkRemovalEngine.Preview(doc, model);
Check(plan.Targets.Single().Source.Contains("cloud-link"), "파일 참조 없는 외부 리소스 링크 포함");
cloud.Resources["resource"].Info.Add("path", "changed"); Reject(() => LinkRemovalEngine.Prepare(doc, model, plan, true), "외부 리소스 연결 변경 차단");
plan = LinkRemovalEngine.Preview(doc, model); cloud.VersionGuid = Guid.NewGuid(); Reject(() => LinkRemovalEngine.Prepare(doc, model, plan, true), "동일 ID의 링크 수정도 revision으로 차단");
doc = new(); doc.Elements.Add(new KeynoteTable { FileReference = new() { ExternalFileReferenceType = ExternalFileReferenceType.KeynoteTable } });
doc.Elements.Add(new Element { FileReference = new() { ExternalFileReferenceType = ExternalFileReferenceType.Material } });
plan = LinkRemovalEngine.Preview(doc, model);
Check(plan.Targets.Count == 0 && plan.Notices.Count == 2 && doc.Elements.Count == 2, "키노트·재료 외부 설정은 유지 및 명시");
doc.Elements.Add(new Element { FileReference = new() { ExternalFileReferenceType = ExternalFileReferenceType.Unknown } });
Check(LinkRemovalEngine.Preview(doc, model).BlockReason.Length > 0, "미확인 외부 참조를 조용히 성공으로 처리하지 않기");
doc = new(); var markup = new Element { FileReference = new() { ExternalFileReferenceType = ExternalFileReferenceType.DWFMarkup } }; doc.Elements.Add(markup);
Check(LinkRemovalEngine.Preview(doc, model).Targets.Single().Kind == "DWF 마크업", "DWF 마크업 외부 참조 포함");
doc = new() { IsWorkshared = true }; doc.Elements.Add(new CADLinkType { OwnedOther = true });
Reject(() => LinkRemovalEngine.Preview(doc, model), "다른 사용자 소유 링크는 강제 취득하지 않기");
doc = new(); var kept = new ImageType(); doc.Elements.Add(kept); doc.RefuseDelete.Add(kept.Id.Value);
Reject(() => LinkRemovalEngine.Preview(doc, model), "삭제 안 되는 정의가 남으면 검사 보류");
doc = new() { FailDelete = true }; doc.Elements.Add(new CADLinkType());
Reject(() => LinkRemovalEngine.Preview(doc, model), "Revit 삭제 거부 전달"); Check(doc.Elements.Count == 1, "삭제 거부도 롤백하여 대상 보존");
doc = new(); doc.Elements.Add(new CADLinkType()); plan = LinkRemovalEngine.Preview(doc, model);
action = LinkRemovalEngine.Prepare(doc, model, plan, true); action.Delete(); doc.Elements.Add(new Element());
Reject(action.Verify, "확정 중 예상 못한 추가 요소 발생 시 저장 차단");
doc = new(); var target = new CADLinkType(); var other = new Element(); doc.Elements.AddRange([target, other]); plan = LinkRemovalEngine.Preview(doc, model);
action = LinkRemovalEngine.Prepare(doc, model, plan, true); action.Delete(); doc.Elements.Remove(other);
Reject(action.Verify, "확정 중 승인 밖 요소 삭제 시 저장 차단");
Console.WriteLine($"TOTAL {count} PASS · 실제 링크 삭제 코드 API 대역 검사; 사용자 RVT 검증 아님");
